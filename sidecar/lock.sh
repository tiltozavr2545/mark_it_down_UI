#!/usr/bin/env bash
set -euo pipefail

# Regenerates the sidecar's dependency lock file for the CURRENT host:
# sidecar/locks/<host>.txt — all packages (including transitive ones) with
# exact versions and wheel sha256 hashes, in requirements.txt format for
# `pip install --require-hashes --no-deps`.
#
# One file per host rather than a single shared one, because the wheels
# differ across hosts (numpy and onnxruntime for macOS x86_64, arm64, and
# Linux are different files with different hashes), and `--require-hashes`
# checks the exact file.
#
# How it works: pip from the downloaded interpreter resolves the
# `markitdown[extras]==version` dependencies in --dry-run mode and produces a
# report (--report) with everything it would install, including the URL and
# sha256 of the chosen wheels. Nothing is actually installed. Needs network
# access (for metadata, and for the wheels themselves if not already in pip's
# cache).
#
# When to run: whenever MARKITDOWN_VERSION/PY_VERSION/PBS_TAG changes in
# common.sh, or when you deliberately want to bump transitive dependencies.
# After that — check `git diff sidecar/locks/`, rebuild (`make sidecar`), and
# run the fixture comparison. The lock changes only through this script and
# only deliberately.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

fetch_interpreter

WORK="$(mktemp -d "${CACHE_DIR}/lock.XXXXXX")"
trap 'rm -rf "${WORK}"' EXIT
tar xzf "${ARCHIVE}" -C "${WORK}"
PY="${WORK}/${PY_REL}"

echo "sidecar: разрешаю зависимости markitdown[${MARKITDOWN_EXTRAS}]==${MARKITDOWN_VERSION} для ${HOST}"
"${PY}" -I -m pip install \
  --disable-pip-version-check --no-input --only-binary=:all: \
  --dry-run --ignore-installed --quiet \
  --report "$(native_path "${WORK}/report.json")" \
  "markitdown[${MARKITDOWN_EXTRAS}]==${MARKITDOWN_VERSION}"

mkdir -p "$(dirname "${LOCK_FILE}")"
"${PY}" -I -X utf8 - "$(native_path "${WORK}/report.json")" "$(native_path "${LOCK_FILE}")" "${HOST}" "${PY_VERSION}" \
  "${MARKITDOWN_VERSION}[${MARKITDOWN_EXTRAS}]" <<'PYEOF'
import json, sys

report, out, host, py, req = sys.argv[1:6]
items = json.load(open(report, encoding="utf-8"))["install"]
lines = []
for it in items:
    meta = it["metadata"]
    sha = it["download_info"]["archive_info"]["hashes"]["sha256"]
    lines.append((meta["name"].lower().replace("_", "-"), meta["version"], sha))
lines.sort()
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write(
        f"# Generated by sidecar/lock.sh — do not edit by hand.\n"
        f"# host={host} python={py} markitdown[extras]={req}\n"
        f"# Install: pip install --require-hashes --no-deps -r <this file>\n"
    )
    for name, version, sha in lines:
        fh.write(f"{name}=={version} --hash=sha256:{sha}\n")
print(f"sidecar: {len(lines)} пакетов -> {out}")
PYEOF
